#!/bin/sh
# Builds dav1d (BSD-2-Clause), VideoLAN's AV1 decoder, for the iPhone app, so
# AV1 video sidecars play on iPhones and iPads without an AV1 hardware decoder
# (before the A17 Pro and M3). Nothing here is committed: the source is cloned
# at a pinned tag and the static libraries, headers, module map, and an
# xcconfig land in ios/Vendor/dav1d/, which ios/Signing.xcconfig includes when
# it exists. Without this build the app still compiles; AV1 then plays only
# where the device decodes it in hardware.
#
# Needs meson and ninja (brew install meson ninja).
# Usage: ios/scripts/build-dav1d.sh
set -eu

TAG=1.5.5
COMMIT=6c7bee685677fd997a431302be4fea8ea4017606
REPO=https://code.videolan.org/videolan/dav1d.git
MIN_IOS=18.0

for tool in meson ninja; do
  command -v "$tool" >/dev/null || { echo "$tool is required (brew install meson ninja)" >&2; exit 1; }
done

ios=$(cd "$(dirname "$0")/.." && pwd)
vendor="$ios/Vendor"
src="$vendor/dav1d-src"
out="$vendor/dav1d"

if [ ! -d "$src/.git" ]; then
  git clone --depth 1 --branch "$TAG" "$REPO" "$src"
fi
actual=$(git -C "$src" rev-parse HEAD)
if [ "$actual" != "$COMMIT" ]; then
  echo "dav1d $TAG is $actual; expected $COMMIT" >&2
  exit 1
fi

rm -rf "$out"
mkdir -p "$out/include"

# build SLICE SDK TARGET PLATFORM: cross-compile the static library for one
# SDK and keep it only if every object carries PLATFORM.
build() {
  dir="$vendor/build-dav1d-$1"
  sdk_path=$(xcrun --sdk "$2" --show-sdk-path)
  rm -rf "$dir"
  mkdir -p "$dir" "$out/$1"
  cat >"$dir/cross.ini" <<EOF
[binaries]
c = ['xcrun', '--sdk', '$2', 'clang']
ar = ['xcrun', '--sdk', '$2', 'ar']
strip = ['xcrun', '--sdk', '$2', 'strip']

[built-in options]
c_args = ['-target', '$3', '-isysroot', '$sdk_path']
c_link_args = ['-target', '$3', '-isysroot', '$sdk_path']

[host_machine]
system = 'darwin'
subsystem = '$( [ "$1" = ios ] && echo ios || echo ios-simulator )'
cpu_family = 'aarch64'
cpu = 'arm64'
endian = 'little'
EOF
  if meson setup "$dir/build" "$src" --cross-file "$dir/cross.ini" \
        --buildtype=release --default-library=static --prefix=/ \
        -Denable_tools=false -Denable_tests=false -Denable_examples=false \
        -Denable_docs=false -Dlogging=false -Dbitdepths=8,16 >"$dir/setup.log" 2>&1 \
     && ninja -C "$dir/build" >"$dir/build.log" 2>&1 \
     && DESTDIR="$dir/stage" meson install -C "$dir/build" >"$dir/install.log" 2>&1 \
     && [ "$(otool -lv "$dir/stage/lib/libdav1d.a" | grep -c "platform $4")" -gt 0 ] \
     && ! otool -lv "$dir/stage/lib/libdav1d.a" | grep "^ *platform" | grep -qv "platform $4"; then
    cp "$dir/stage/lib/libdav1d.a" "$out/$1/libdav1d.a"
    [ -d "$out/include/dav1d" ] || cp -R "$dir/stage/include/dav1d" "$out/include/dav1d"
    return 0
  fi
  rm -rf "$out/$1"
  return 1
}

build ios iphoneos "arm64-apple-ios$MIN_IOS" IOS
echo "built: device slice"
if build sim iphonesimulator "arm64-apple-ios$MIN_IOS-simulator" IOSSIMULATOR; then
  echo "built: simulator slice"
else
  echo "skipped: simulator slice (see $vendor/build-dav1d-sim/*.log); software AV1 is unavailable in the simulator" >&2
fi

cp "$src/COPYING" "$out/COPYING"
# DAV1D_ERR is a function-like macro, which does not import into Swift.
cat >"$out/include/vtamp_dav1d.h" <<'EOF'
#ifndef VTAMP_DAV1D_H
#define VTAMP_DAV1D_H
#include <errno.h>
#include "dav1d/dav1d.h"
static inline int vtamp_dav1d_again(void) { return DAV1D_ERR(EAGAIN); }
#endif
EOF
cat >"$out/include/module.modulemap" <<'EOF'
module CDav1d {
    header "vtamp_dav1d.h"
    export *
}
EOF

# Namespaced settings: ios/Signing.xcconfig adds them to the build settings,
# so the libvpx and dav1d builds can be present together.
{
  echo "// Generated by ios/scripts/build-dav1d.sh for dav1d $TAG; not committed."
  echo "VTAMP_DAV1D_INCLUDE = \$(SRCROOT)/Vendor/dav1d/include"
  for slice in ios sim; do
    [ -f "$out/$slice/libdav1d.a" ] || continue
    if [ "$slice" = ios ]; then sdk="iphoneos*"; else sdk="iphonesimulator*"; fi
    echo "VTAMP_DAV1D_LIBS[sdk=$sdk] = \$(SRCROOT)/Vendor/dav1d/$slice"
    echo "VTAMP_DAV1D_LDFLAGS[sdk=$sdk] = -ldav1d"
    echo "VTAMP_DAV1D_CONDITIONS[sdk=$sdk] = VTAMP_DAV1D"
  done
} >"$out/dav1d.xcconfig"
echo "wrote $out/dav1d.xcconfig"
